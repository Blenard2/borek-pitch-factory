"""BAP-9: Discovery documents stored before the wording changes stay valid, unchanged and usable.

The fixtures in tests/fixtures/stored_discovery were generated by the earlier code itself:

* bap5_researched_1_0       ad732c3 (BAP-5), website research record 1.0
* bap10_researched_1_1      8d705d8 (BAP-10), research 1.1 with the company background page
* bap10_without_research    8d705d8, user context only
* bap10_live_researched_1_1 8d705d8, live mode (fake model) with research 1.1

Validation compares a stored page manifest with the layout rebuilt from the stored content, so
every text the layout reads at that time must still produce exactly the stored pages.
"""

from __future__ import annotations

import copy
import json
from pathlib import Path
from uuid import UUID

import pytest
from fastapi.testclient import TestClient

from app.main import create_app
from app.services.data.memory_store import get_memory_store, reset_memory_store
from services.framework.discovery_analysis.layout import build_page_manifest
from services.framework.discovery_analysis.model import validate_discovery_analysis
from services.presentation.master_deck.plan import build_master_plan
from tests.unit.api.test_master_presentation_v2_api import OWNER, headers

STORED = Path(__file__).resolve().parents[2] / "fixtures" / "stored_discovery"
DOCUMENTS = sorted(path.stem for path in STORED.glob("*.json"))


def stored(name: str) -> dict:
    return json.loads((STORED / f"{name}.json").read_text(encoding="utf-8"))


def test_all_representative_documents_are_present() -> None:
    assert DOCUMENTS == ["bap10_live_researched_1_1", "bap10_researched_1_1", "bap10_without_research", "bap5_researched_1_0"]


@pytest.mark.parametrize("name", DOCUMENTS)
def test_a_stored_document_still_validates_and_rebuilds_byte_for_byte(name: str) -> None:
    paper = stored(name)
    original = copy.deepcopy(paper)
    validate_discovery_analysis(paper)
    assert paper == original, "validation never rewrites the stored document"
    assert build_page_manifest(paper) == original["page_manifest"], "the stored pages are exactly what the layout rebuilds"


@pytest.mark.parametrize("name", DOCUMENTS)
def test_a_stored_draft_can_be_approved_without_its_content_changing(name: str) -> None:
    reset_memory_store()
    with TestClient(create_app()) as client:
        created = client.post("/opportunities", headers=headers(), json={"client_name": "Hansa Präzisionsteile", "opportunity_name": "AI introduction", "department": "Sales"})
        opportunity_id = created.json()["id"]
        paper = stored(name)
        paper["opportunity_id"] = opportunity_id
        store = get_memory_store()
        store.update_opportunity(opportunity_id=UUID(opportunity_id), user_id=OWNER, updates={"discovery_paper": copy.deepcopy(paper)})
        store.create_discovery_paper_version(opportunity_id=UUID(opportunity_id), user_id=OWNER, document_id=UUID(paper["document_id"]), paper_json=copy.deepcopy(paper))
        approved = client.post(f"/opportunities/{opportunity_id}/discovery-paper/approve", headers=headers())
        assert approved.status_code == 200, approved.text
        body = approved.json()
        assert body["status"] == "approved"
        expected = {**paper, "latest_approved_version_id": body["id"]}
        assert body["paper_json"] == expected, "approval keeps the stored content and pages as they are"
        read_back = client.get(f"/opportunities/{opportunity_id}/discovery-paper/approved", headers=headers()).json()
        assert read_back["paper_json"]["page_manifest"] == paper["page_manifest"]
        # The approved stored document still feeds Master Presentation V1.
        plan = build_master_plan({"id": body["id"], "opportunity_id": opportunity_id, "document_id": paper["document_id"], "status": "approved", "paper_json": read_back["paper_json"]})
        assert plan["slides"][-1]["borekSlide"]["title"] == "Let’s talk"
